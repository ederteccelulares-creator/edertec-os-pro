create table if not exists public.support_tickets (
 id uuid primary key default gen_random_uuid(),
 company_id uuid not null references public.companies(id) on delete cascade,
 created_by uuid not null references auth.users(id) on delete restrict,
 ticket_number bigint generated by default as identity unique,
 subject text not null check(char_length(trim(subject)) between 4 and 160),
 description text not null check(char_length(trim(description)) between 10 and 10000),
 category text not null default 'general' check(category in ('general','technical','billing','suggestion')),
 priority text not null default 'normal' check(priority in ('low','normal','high','urgent')),
 status text not null default 'open' check(status in ('open','in_progress','waiting_company','resolved','closed')),
 assigned_to uuid references auth.users(id) on delete set null,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(),
 resolved_at timestamptz,
 unique(id,company_id)
);
create table if not exists public.support_ticket_messages (
 id uuid primary key default gen_random_uuid(),
 ticket_id uuid not null references public.support_tickets(id) on delete cascade,
 company_id uuid not null references public.companies(id) on delete cascade,
 author_id uuid not null references auth.users(id) on delete restrict,
 body text not null check(char_length(trim(body)) between 1 and 10000),
 is_internal boolean not null default false,
 created_at timestamptz not null default now(),
 constraint support_ticket_messages_ticket_company_fkey foreign key(ticket_id,company_id) references public.support_tickets(id,company_id) on delete cascade
);
create index if not exists support_tickets_company_status_updated_idx on public.support_tickets(company_id,status,updated_at desc);
create index if not exists support_ticket_messages_ticket_created_idx on public.support_ticket_messages(ticket_id,created_at);
alter table public.support_tickets enable row level security;
alter table public.support_ticket_messages enable row level security;
revoke all on public.support_tickets,public.support_ticket_messages from anon;
grant select,insert,update on public.support_tickets to authenticated;
grant select,insert on public.support_ticket_messages to authenticated;
drop policy if exists "company members read own support tickets" on public.support_tickets;
create policy "company members read own support tickets" on public.support_tickets for select to authenticated using(public.is_company_member(company_id));
drop policy if exists "company members create own support tickets" on public.support_tickets;
create policy "company members create own support tickets" on public.support_tickets for insert to authenticated with check(created_by=(select auth.uid()) and public.is_company_member(company_id));
drop policy if exists "company members update own support tickets" on public.support_tickets;
drop policy if exists "platform admins manage support tickets" on public.support_tickets;
create policy "platform admins manage support tickets" on public.support_tickets for all to authenticated using(public.is_platform_admin()) with check(public.is_platform_admin());
drop policy if exists "company members read support messages" on public.support_ticket_messages;
create policy "company members read support messages" on public.support_ticket_messages for select to authenticated using(is_internal=false and public.is_company_member(company_id));
drop policy if exists "company members create support messages" on public.support_ticket_messages;
create policy "company members create support messages" on public.support_ticket_messages for insert to authenticated with check(author_id=(select auth.uid()) and is_internal=false and public.is_company_member(company_id) and exists(select 1 from public.support_tickets t where t.id=support_ticket_messages.ticket_id and t.company_id=support_ticket_messages.company_id));
drop policy if exists "platform admins read support messages" on public.support_ticket_messages;
create policy "platform admins read support messages" on public.support_ticket_messages for select to authenticated using(public.is_platform_admin());
drop policy if exists "platform admins create support messages" on public.support_ticket_messages;
create policy "platform admins create support messages" on public.support_ticket_messages for insert to authenticated with check(public.is_platform_admin() and author_id=(select auth.uid()));
