create table if not exists public.company_simple_receipts (
 id uuid primary key default gen_random_uuid(),
 company_id uuid not null references public.companies(id) on delete cascade,
 receipt_number bigint generated by default as identity,
 customer_name text not null,
 description text not null,
 amount numeric(14,2) not null check(amount>0),
 receipt_date date not null default current_date,
 notes text,
 created_by uuid references auth.users(id),
 created_at timestamptz not null default now(),
 unique(company_id,receipt_number)
);
create table if not exists public.company_part_purchases (
 id uuid primary key default gen_random_uuid(),
 company_id uuid not null references public.companies(id) on delete cascade,
 brand text not null,
 part_description text not null,
 amount numeric(14,2) not null check(amount>0),
 purchase_date date not null default current_date,
 supplier_name text not null,
 warranty_days integer not null check(warranty_days in (30,60,90)),
 warranty_until date generated always as (purchase_date + warranty_days) stored,
 created_by uuid references auth.users(id),
 created_at timestamptz not null default now()
);
create index if not exists company_simple_receipts_company_created_idx on public.company_simple_receipts(company_id,created_at desc);
create index if not exists company_part_purchases_company_date_idx on public.company_part_purchases(company_id,purchase_date desc);
alter table public.company_simple_receipts enable row level security;
alter table public.company_part_purchases enable row level security;
drop policy if exists company_simple_receipts_manage on public.company_simple_receipts;
create policy company_simple_receipts_manage on public.company_simple_receipts for all to authenticated
 using(public.has_company_role(company_id,array['owner','admin','manager']::text[]))
 with check(public.has_company_role(company_id,array['owner','admin','manager']::text[]));
drop policy if exists company_part_purchases_manage on public.company_part_purchases;
create policy company_part_purchases_manage on public.company_part_purchases for all to authenticated
 using(public.has_company_role(company_id,array['owner','admin','manager']::text[]))
 with check(public.has_company_role(company_id,array['owner','admin','manager']::text[]));
grant select,insert,update,delete on public.company_simple_receipts,public.company_part_purchases to authenticated;
