-- Eparts: estrutura comercial exclusiva, isolada por company_id.
-- Comissão padrão fixa: 12% para Eparts e 88% para o fornecedor.
create table if not exists public.eparts_brands (
 id uuid primary key default gen_random_uuid(), company_id uuid not null references public.companies(id) on delete cascade,
 name text not null, is_active boolean not null default true, created_at timestamptz not null default now(),
 unique(company_id,name), unique(id,company_id)
);
create table if not exists public.eparts_suppliers (
 id uuid primary key default gen_random_uuid(), company_id uuid not null references public.companies(id) on delete cascade,
 user_id uuid references auth.users(id) on delete set null, name text not null, contact_name text, email text, phone text,
 document text, notes text, is_active boolean not null default true, created_at timestamptz not null default now(),
 unique(id,company_id)
);
create table if not exists public.eparts_customers (
 id uuid primary key default gen_random_uuid(), company_id uuid not null references public.companies(id) on delete cascade,
 name text not null, email text, phone text, document text, address jsonb not null default '{}'::jsonb,
 created_at timestamptz not null default now(), unique(id,company_id)
);
create table if not exists public.eparts_products (
 id uuid primary key default gen_random_uuid(), company_id uuid not null references public.companies(id) on delete cascade,
 supplier_id uuid not null, brand_id uuid, name text not null, sku text, description text, image_url text,
 cost_price numeric(12,2) not null default 0 check(cost_price>=0), sale_price numeric(12,2) not null default 0 check(sale_price>=0),
 stock_quantity numeric(12,3) not null default 0 check(stock_quantity>=0), is_active boolean not null default true,
 show_in_catalog boolean not null default true, created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 foreign key(supplier_id,company_id) references public.eparts_suppliers(id,company_id),
 foreign key(brand_id,company_id) references public.eparts_brands(id,company_id), unique(id,company_id)
);
create unique index if not exists eparts_products_company_sku_uidx on public.eparts_products(company_id,sku) where sku is not null and sku<>'';
create table if not exists public.eparts_sales (
 id uuid primary key default gen_random_uuid(), company_id uuid not null references public.companies(id) on delete cascade,
 customer_id uuid, order_number bigint generated by default as identity, source text not null default 'admin' check(source in('admin','catalog')),
 status text not null default 'pending' check(status in('pending','confirmed','processing','shipped','delivered','cancelled')),
 payment_status text not null default 'pending' check(payment_status in('pending','paid','partially_paid','refunded')),
 payment_method text, subtotal numeric(12,2) not null default 0 check(subtotal>=0), discount numeric(12,2) not null default 0 check(discount>=0),
 shipping_amount numeric(12,2) not null default 0 check(shipping_amount>=0), total_amount numeric(12,2) not null default 0 check(total_amount>=0),
 eparts_commission_rate numeric(5,2) not null default 12.00 check(eparts_commission_rate=12.00),
 eparts_commission_amount numeric(12,2) not null default 0, supplier_amount numeric(12,2) not null default 0,
 customer_name text, customer_email text, customer_phone text, customer_address jsonb not null default '{}'::jsonb,
 notes text, created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 foreign key(customer_id,company_id) references public.eparts_customers(id,company_id), unique(id,company_id)
);
create table if not exists public.eparts_sale_items (
 id uuid primary key default gen_random_uuid(), company_id uuid not null references public.companies(id) on delete cascade,
 sale_id uuid not null, product_id uuid not null, supplier_id uuid not null, product_name text not null, sku text,
 quantity numeric(12,3) not null check(quantity>0), unit_price numeric(12,2) not null check(unit_price>=0),
 line_total numeric(12,2) not null check(line_total>=0), eparts_commission_amount numeric(12,2) not null default 0,
 supplier_amount numeric(12,2) not null default 0, created_at timestamptz not null default now(),
 foreign key(sale_id,company_id) references public.eparts_sales(id,company_id) on delete cascade,
 foreign key(product_id,company_id) references public.eparts_products(id,company_id),
 foreign key(supplier_id,company_id) references public.eparts_suppliers(id,company_id)
);
create table if not exists public.eparts_supplier_payouts (
 id uuid primary key default gen_random_uuid(), company_id uuid not null references public.companies(id) on delete cascade,
 supplier_id uuid not null, sale_id uuid, amount numeric(12,2) not null check(amount>0),
 payment_method text not null check(payment_method in('pix','cash','transfer','bank_slip','card','other')),
 paid_at timestamptz not null default now(), reference text, notes text, created_by uuid references auth.users(id) on delete set null,
 created_at timestamptz not null default now(), foreign key(supplier_id,company_id) references public.eparts_suppliers(id,company_id),
 foreign key(sale_id,company_id) references public.eparts_sales(id,company_id)
);
create index if not exists eparts_products_catalog_idx on public.eparts_products(company_id,is_active,show_in_catalog);
create index if not exists eparts_sales_supplier_status_idx on public.eparts_sale_items(company_id,supplier_id,sale_id);
create index if not exists eparts_payouts_supplier_date_idx on public.eparts_supplier_payouts(company_id,supplier_id,paid_at desc);
alter table public.eparts_brands enable row level security;
alter table public.eparts_suppliers enable row level security;
alter table public.eparts_customers enable row level security;
alter table public.eparts_products enable row level security;
alter table public.eparts_sales enable row level security;
alter table public.eparts_sale_items enable row level security;
alter table public.eparts_supplier_payouts enable row level security;
do $$
declare t text;
begin
 foreach t in array array['eparts_brands','eparts_suppliers','eparts_customers','eparts_products','eparts_sales','eparts_sale_items','eparts_supplier_payouts'] loop
  execute format('drop policy if exists %I on public.%I',t||'_company_members',t);
  execute format('create policy %I on public.%I for all to authenticated using (exists(select 1 from public.company_members m where m.company_id=%I.company_id and m.user_id=auth.uid() and m.is_active=true and m.role in (''owner'',''admin'',''manager''))) with check (exists(select 1 from public.company_members m where m.company_id=%I.company_id and m.user_id=auth.uid() and m.is_active=true and m.role in (''owner'',''admin'',''manager'')))',t||'_company_members',t,t,t);
 end loop;
end $$;
drop policy if exists eparts_supplier_self_read on public.eparts_suppliers;
create policy eparts_supplier_self_read on public.eparts_suppliers for select to authenticated using(user_id=auth.uid());
drop policy if exists eparts_supplier_products_read on public.eparts_products;
create policy eparts_supplier_products_read on public.eparts_products for select to authenticated using(
 exists(select 1 from public.eparts_suppliers s where s.id=eparts_products.supplier_id and s.company_id=eparts_products.company_id and s.user_id=auth.uid()));
drop policy if exists eparts_supplier_sale_items_read on public.eparts_sale_items;
create policy eparts_supplier_sale_items_read on public.eparts_sale_items for select to authenticated using(
 exists(select 1 from public.eparts_suppliers s where s.id=eparts_sale_items.supplier_id and s.company_id=eparts_sale_items.company_id and s.user_id=auth.uid()));
drop policy if exists eparts_supplier_sales_read on public.eparts_sales;
create policy eparts_supplier_sales_read on public.eparts_sales for select to authenticated using(
 exists(select 1 from public.eparts_sale_items i join public.eparts_suppliers s on s.id=i.supplier_id and s.company_id=i.company_id
 where i.sale_id=eparts_sales.id and i.company_id=eparts_sales.company_id and s.user_id=auth.uid()));
drop policy if exists eparts_supplier_payouts_read on public.eparts_supplier_payouts;
create policy eparts_supplier_payouts_read on public.eparts_supplier_payouts for select to authenticated using(
 exists(select 1 from public.eparts_suppliers s where s.id=eparts_supplier_payouts.supplier_id and s.company_id=eparts_supplier_payouts.company_id and s.user_id=auth.uid()));
